// `baseline-build.ps1`: the script the captain runs elevated to build a flavor's golden (ticket 24,
// docs/baselines.md). `arashouse baseline build` writes it into the bundle with the SHA-256 of every
// file it runs or reads pinned in its text, so a bundle changed after review does not run. It
// checks the pins, elevation and Node, reads the optional secrets (hidden prompts or the captain's own
// DPAPI files), and starts the build (src/broker/baseline-main.ts) under Node, which does the steps.

import { win32 } from "node:path";
import { FLAVORS, type FlavorKey } from "./flavors.js";
import { assertValidRoot } from "./guards.js";
import { DEFAULT_INSTALL_ROOT, buildNames, buildScratch, goldenDir } from "./names.js";
import { MIN_NODE_MAJOR, psQuote, type AppFile } from "./setup-host.js";

export const BUILD_SCRIPT_NAME = "baseline-build.ps1";

/** The environment variables the script hands the secrets to Node in (src/broker/baseline-main.ts reads and removes them). */
export const BUILD_SECRET_ENV = { licence: "ARASHOUSE_BUILD_LICENCE", adminPassword: "ARASHOUSE_BUILD_ADMIN_PASSWORD" } as const;

/** `<bundle>\plan.json`: what the CLI checked, for the build to hold the bundle to. */
export interface BundlePlan {
  readonly schema: 1;
  readonly flavor: string;
  readonly msiSha256: string;
  readonly minFreeDiskGb: number;
  readonly version: string;
}

export const PLAN_FILE = "plan.json";
/** The build's report, which `baseline-main.js` writes next to the script. */
export const RESULT_FILE = "result.json";

export interface PinnedFile {
  /** Relative to the bundle, backslash-separated. */
  readonly path: string;
  readonly sha256: string;
}

export interface BuildScriptOptions {
  readonly flavor: FlavorKey;
  readonly version: string;
  readonly root?: string;
  /** Every file of the bundle the script trusts: `app\...`, `package.json`, `plan.json`, the steps script, the media. */
  readonly pinned: readonly (PinnedFile | AppFile)[];
}

const SHA256 = /^[0-9a-f]{64}$/;
const BUNDLE_PATH = /^[A-Za-z0-9_.-]+(\\[A-Za-z0-9_.-]+)*$/;
const VERSION = /^[0-9A-Za-z.+-]{1,64}$/;

export function renderBaselineBuildScript(options: BuildScriptOptions): string {
  const root = assertValidRoot(options.root ?? DEFAULT_INSTALL_ROOT);
  if (!VERSION.test(options.version)) throw new Error("the version must be 1 to 64 letters, digits, '.', '+' or '-'");
  const seen = new Set<string>();
  for (const f of options.pinned) {
    if (!BUNDLE_PATH.test(f.path) || f.path.split("\\").some((s) => s === "." || s === "..")) throw new Error(`unusable bundle path "${f.path}"`);
    if (!SHA256.test(f.sha256)) throw new Error(`the SHA-256 of ${f.path} is not 64 hex digits`);
    if (seen.has(f.path.toLowerCase())) throw new Error(`the bundle lists ${f.path} twice`);
    seen.add(f.path.toLowerCase());
  }
  for (const needed of ["app\\broker\\baseline-main.js", "package.json", "plan.json", "baseline-steps.ps1"]) {
    if (!seen.has(needed)) throw new Error(`the bundle has no ${needed}`);
  }
  const f = FLAVORS[options.flavor];
  const names = buildNames(options.flavor, root);
  const scratch = buildScratch(options.flavor, root);
  const pins = options.pinned.map((p) => `    @{ path = ${psQuote(p.path)}; sha256 = ${psQuote(p.sha256)} }`).join("\n");

  return `# baseline-build.ps1: builds the golden baseline of flavor ${options.flavor} (${f.release}) for arashouse (ticket 24, docs/baselines.md),
# generated by \`arashouse baseline build ${options.flavor}\` ${options.version}. Run it in an elevated Windows PowerShell 5.1:
#
#   baseline-build.ps1                                   the plan: checks the bundle, changes nothing (no elevation needed)
#   baseline-build.ps1 -Apply                            build the golden (the login check is skipped: it needs a licence key)
#   baseline-build.ps1 -Apply -AskLicence -AskAdminPassword
#                                                        ... and log in as root: both asked at hidden prompts
#   baseline-build.ps1 -Apply -LicenceFile <f> -AdminPasswordFile <f>
#                                                        ... the same, from files of ConvertFrom-SecureString (your own DPAPI); the
#                                                        licence file holds the key, or the JSON {lic_key, act_key, lic_type, company}
#   baseline-build.ps1 -Apply -Replace                   rebuild over an existing golden (arashouse marked its slots dirty)
#   baseline-build.ps1 -Apply -Cleanup                   remove what a failed build left of the throw-away instance, nothing else
#
# What -Apply changes: it installs the MSI (a copy with its own ProductCode) into ${names.dir} as the
# web alias /${names.alias} with pools ${scratch.poolPrefix}<role>, restores the shipped ${f.backups.coreAndSolutions} as database
# ${names.database} with logins ${scratch.logins.dbo} and ${scratch.logins.reg} (Windows authentication as you, no sa), checks it serves,
# copies its tree and backups to ${goldenDir(options.flavor, root)}, then removes the throw-away instance (alias, pools, database, logins,
# product registration, folders under ${win32.join(root, "golden-build")}) and checks that nothing outside arashouse changed (names and
# hashes only: the captain's install roots, every IIS application and pool not named ah-*, the agent services, the Aras products).
# Nothing is written under Program Files. No secret is printed, logged or written: the licence key and the admin password (when given)
# go to the build's Node process in its environment only and are blanked from the copied configs; the MSI log is deleted.
# Exit codes: 0 ok, 1 a step failed (the report says which; the throw-away instance is removed), 2 refused arguments,
# 3 the bundle does not match its pins, 4 not elevated, 5 no usable node.exe.
param(
    [switch]$Apply,
    [switch]$Replace,
    [switch]$Cleanup,
    [switch]$AskLicence,
    [switch]$AskAdminPassword,
    [string]$LicenceFile,
    [string]$AdminPasswordFile
)
$ErrorActionPreference = 'Stop'
$Flavor = ${psQuote(options.flavor)}
$Bundle = ${psQuote(scratch.bundleDir)}
$Pins = @(
${pins}
)

function Stop-Build([int]$Code, [string]$Message) { [Console]::Error.WriteLine("error: $Message"); exit $Code }

if ($PSScriptRoot -ine $Bundle) { Stop-Build 2 "run this script from $Bundle, where arashouse baseline build wrote it" }
if ($Cleanup -and ($Replace -or $AskLicence -or $AskAdminPassword -or $LicenceFile -or $AdminPasswordFile)) { Stop-Build 2 '-Cleanup takes no other switch' }
if ($AskLicence -and $LicenceFile) { Stop-Build 2 'give -AskLicence or -LicenceFile, not both' }
if ($AskAdminPassword -and $AdminPasswordFile) { Stop-Build 2 'give -AskAdminPassword or -AdminPasswordFile, not both' }

Write-Host "check: the $($Pins.Count) files of the bundle against their SHA-256"
foreach ($p in $Pins) {
    $file = Join-Path $Bundle $p.path
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { Stop-Build 3 "the bundle has no $($p.path)" }
    $h = (Get-FileHash -Algorithm SHA256 -LiteralPath $file).Hash.ToLowerInvariant()
    if ($h -ne $p.sha256) { Stop-Build 3 "$($p.path) does not match the SHA-256 this script was generated with; run arashouse baseline build again" }
}
$extra = @(Get-ChildItem -LiteralPath (Join-Path $Bundle 'app') -Recurse -File | Where-Object { $rel = $_.FullName.Substring($Bundle.Length + 1); -not ($Pins | Where-Object { $_.path -ieq $rel }) })
if ($extra.Count -gt 0) { Stop-Build 3 "the bundle's app folder holds a file this script does not pin: $($extra[0].FullName)" }

if (-not $Apply) {
    Write-Host "would do: build the $Flavor golden at ${goldenDir(options.flavor, root)} (see the header of this script); run again with -Apply, elevated"
    exit 0
}
$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { Stop-Build 4 'run this in an elevated PowerShell (Run as administrator), or without -Apply' }

# Node, as setup-host.ps1 finds it: the default install, version ${MIN_NODE_MAJOR} or newer.
$node = Join-Path $env:ProgramFiles 'nodejs\\node.exe'
if (-not (Test-Path -LiteralPath $node)) { $cmd = Get-Command node.exe -ErrorAction SilentlyContinue; if ($cmd) { $node = $cmd.Source } }
if (-not (Test-Path -LiteralPath $node)) { Stop-Build 5 'node.exe was not found' }
$nodeVersion = (& $node --version) -replace '^v', ''
if ([int]($nodeVersion.Split('.')[0]) -lt ${MIN_NODE_MAJOR}) { Stop-Build 5 "node.exe $nodeVersion is older than ${MIN_NODE_MAJOR}" }

function ConvertTo-Plain([Security.SecureString]$Secure) {
    $ptr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($Secure)
    try { return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr) }
}
function Read-SecretFile([string]$Path, [string]$What) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { Stop-Build 2 "no $What file at $Path" }
    try { return (ConvertTo-SecureString -String ([IO.File]::ReadAllText($Path).Trim())) } catch { Stop-Build 2 "the $What file cannot be read with your DPAPI key (it must be ConvertFrom-SecureString output of this Windows user)" }
}
$licence = $null
$admin = $null
if ($AskLicence) { $licence = Read-Host -AsSecureString -Prompt 'Aras licence key for line ${f.licence.line} (hidden)' }
if ($LicenceFile) { $licence = Read-SecretFile $LicenceFile 'licence key' }
if ($AskAdminPassword) { $admin = Read-Host -AsSecureString -Prompt 'Password of the shipped backup''s root login (hidden)' }
if ($AdminPasswordFile) { $admin = Read-SecretFile $AdminPasswordFile 'admin password' }

$nodeArgs = @((Join-Path $Bundle 'app\\broker\\baseline-main.js'))
if ($Replace) { $nodeArgs += '--replace' }
if ($Cleanup) { $nodeArgs += '--cleanup' }
try {
    if ($licence) { [Environment]::SetEnvironmentVariable(${psQuote(BUILD_SECRET_ENV.licence)}, (ConvertTo-Plain $licence), 'Process') }
    if ($admin) { [Environment]::SetEnvironmentVariable(${psQuote(BUILD_SECRET_ENV.adminPassword)}, (ConvertTo-Plain $admin), 'Process') }
    Push-Location $env:SystemRoot
    try { & $node @nodeArgs; $code = $LASTEXITCODE } finally { Pop-Location }
} finally {
    [Environment]::SetEnvironmentVariable(${psQuote(BUILD_SECRET_ENV.licence)}, $null, 'Process')
    [Environment]::SetEnvironmentVariable(${psQuote(BUILD_SECRET_ENV.adminPassword)}, $null, 'Process')
}
exit $code
`;
}
